#!/usr/bin/env bash
# =============================================================================
# agent-spec-render-skills.sh
# Render every downstream agent format from the ONE hand-edited source:
#   skills/claude/<name>/SKILL.md
#
# Cursor and the generic agents read the same SKILL.md shape as Claude, so the
# installer copies skills/claude/ straight to .cursor/skills/ and .agents/skills/ —
# no separate trees to drift. Only the two flat formats need rendering:
#
#   .windsurfrules                     Windsurf (single concatenated file)
#   .github/copilot-instructions.md    Copilot / Codex (single concatenated file)
#
# Run after editing anything under skills/claude/. Never edit the generated files
# by hand — this script overwrites them.
#
# Usage: ./bin/agent-spec-render-skills.sh [--check]
#   --check   render to a temp dir and diff; exit 1 if the tree is stale.
# =============================================================================
set -eo pipefail

GREEN='\033[0;32m'; YELLOW='\033[1;33m'; RED='\033[0;31m'; NC='\033[0m'

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="${ROOT}/skills/claude"
[ -d "${SRC}" ] || { echo "✗ not found: ${SRC}" >&2; exit 1; }

CHECK="false"
[ "${1:-}" = "--check" ] && CHECK="true"

if [ "$CHECK" = "true" ]; then
  OUT="$(mktemp -d)"; trap 'rm -rf "${OUT}"' EXIT
else
  OUT="${ROOT}"
fi

# --- helpers ---------------------------------------------------------------
# A SKILL.md is: --- / frontmatter / --- / body.
frontmatter() { awk 'NR==1&&$0=="---"{f=1;print;next} f&&$0=="---"{print;exit} f{print}' "$1"; }
body()        { awk 'NR==1&&$0=="---"{f=1;next} f&&$0=="---"{f=0;b=1;next} b{print}' "$1"; }
# Same body with its leading H1 removed — for the flat files, where each skill is
# already an H2 section and a nested H1 would invert the heading order.
body_no_h1()  { body "$1" | awk 'NR==1&&$0==""{next} !done&&/^# /{done=1;skip=1;next} skip&&$0==""{skip=0;next} {print}'; }

# description: may be a quoted scalar or a folded (>-) block. Join either into one line.
description() {
  awk '
    /^description:/ {
      sub(/^description:[[:space:]]*/, "")
      if ($0 == ">-" || $0 == ">" || $0 == "|" || $0 == "|-") { fold=1; next }
      print; exit
    }
    fold {
      if ($0 ~ /^[a-zA-Z_-]+:/ || $0 == "---") exit
      sub(/^[[:space:]]+/, ""); printf "%s ", $0
    }
    END { if (fold) print "" }
  ' "$1" | sed 's/^"//; s/"$//; s/[[:space:]]*$//'
}

mkdir -p "${OUT}/.github"

WINDSURF="${OUT}/.windsurfrules"
COPILOT="${OUT}/.github/copilot-instructions.md"

{
  echo "# Windsurf Project Rules & Skills"
  echo ""
  echo "> Generated by bin/agent-spec-render-skills.sh from skills/claude/. Do not edit."
  echo ""
} > "${WINDSURF}"

{
  echo "# Project Skills & Instructions"
  echo ""
  echo "> Generated by bin/agent-spec-render-skills.sh from skills/claude/. Do not edit."
  echo ""
} > "${COPILOT}"

count=0
for dir in "${SRC}"/*/; do
  name="$(basename "${dir}")"
  src="${dir}SKILL.md"
  [ -f "${src}" ] || continue

  desc="$(description "${src}")"

  # Windsurf + Copilot: one flat file each, every skill as a section.
  flat="$(body_no_h1 "${src}")"
  { printf '## /%s\n\n%s\n\n' "${name}" "${flat}"; } >> "${WINDSURF}"
  { printf '## /%s\n\n**Description**: %s\n\n%s\n\n' "${name}" "${desc}" "${flat}"; } >> "${COPILOT}"

  count=$((count + 1))
done

if [ "$CHECK" = "true" ]; then
  stale=0
  for target in .windsurfrules .github/copilot-instructions.md; do
    if ! diff -q "${ROOT}/${target}" "${OUT}/${target}" >/dev/null 2>&1; then
      echo -e "${RED}✗ stale:${NC} ${target}"; stale=1
    fi
  done
  [ "$stale" = "0" ] && echo -e "${GREEN}✓${NC} generated files are current (${count} skills)"
  exit "$stale"
fi

echo -e "${GREEN}✓${NC} rendered ${count} skills → .windsurfrules, .github/copilot-instructions.md"
