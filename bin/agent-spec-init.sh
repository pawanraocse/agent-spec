#!/usr/bin/env bash
# =============================================================================
# agent-spec-init.sh
# Initialize agent-spec framework in the current project directory.
# Usage: ./bin/agent-spec-init.sh [--force]
# =============================================================================

set -eo pipefail # Remove -u to handle unbound BASH_SOURCE

GREEN='\033[0;32m'; BLUE='\033[0;34m'; YELLOW='\033[1;33m'; NC='\033[0m'

GITHUB_RAW_URL="https://raw.githubusercontent.com/pawanraocse/agent-spec/main"

# Detect if we are running locally or remotely
if [ -n "${BASH_SOURCE[0]:-}" ] && [ -f "${BASH_SOURCE[0]}" ]; then
  AGENT_SPEC_HOME="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
  MODE="LOCAL"
else
  AGENT_SPEC_HOME="/tmp/agent-spec-$(date +%s)"
  MODE="REMOTE"
  mkdir -p "${AGENT_SPEC_HOME}"
  echo -e "${YELLOW}Downloading framework from GitHub...${NC}"
  curl -sSL "https://github.com/pawanraocse/agent-spec/archive/refs/heads/main.tar.gz" | tar -xz -C "${AGENT_SPEC_HOME}" --strip-components=1
fi

# Cleanup on exit if remote
if [ "$MODE" = "REMOTE" ]; then
  trap 'rm -rf "${AGENT_SPEC_HOME}"' EXIT
fi

PROJECT_ROOT="$(pwd)"
DATE=$(date '+%Y-%m-%d')
DATETIME=$(date '+%Y-%m-%dT%H:%M:%S')

FORCE_OVERWRITE="false"
for arg in "$@"; do
  if [ "$arg" = "--force" ]; then
    FORCE_OVERWRITE="true"
  fi
done


echo -e "${BLUE}╔══════════════════════════════════════════╗${NC}"
echo -e "${BLUE}║         agent-spec init v1.0.0           ║${NC}"
echo -e "${BLUE}╚══════════════════════════════════════════╝${NC}"
echo ""
echo -e "📂 Project root: ${PROJECT_ROOT}"
echo -e "🏠 agent-spec home: ${AGENT_SPEC_HOME}"
echo ""

# ---------------------------------------------------------------------------
# 1. Create .agent-spec/ directory structure
# ---------------------------------------------------------------------------
echo -e "${YELLOW}[1/6] Creating .agent-spec/ directory...${NC}"
mkdir -p "${PROJECT_ROOT}/.agent-spec/graph"
mkdir -p "${PROJECT_ROOT}/.agent-spec/sdlc"

# Project Index is now auto-generated by graphify-build.py during the init process.

# Constitution
if [ ! -f "${PROJECT_ROOT}/.agent-spec/CONSTITUTION.md" ]; then
  cp "${AGENT_SPEC_HOME}/templates/project-constitution.md" \
     "${PROJECT_ROOT}/.agent-spec/CONSTITUTION.md"
  echo -e "  ✅ Created .agent-spec/CONSTITUTION.md"
fi

# Session Snapshot
cat > "${PROJECT_ROOT}/.agent-spec/SESSION-SNAPSHOT.md" << EOF
# Session Snapshot — ${DATETIME}

> Created by agent-spec init. Update this after every working session.

## Session Summary
Initial project setup with agent-spec framework.

## Current Pipeline Gate
Gate 1: DISCOVERY

## Last Task Completed
agent-spec initialization

## Files Changed
- (none yet)

## Open Items
- [ ] Review auto-generated PROJECT-INDEX.md and resolve any [TODO] placeholders.
- [ ] Fill in .agent-spec/CONSTITUTION.md with project rules

## Next Session: Load These Files
- .agent-spec/PROJECT-INDEX.md
- .agent-spec/graph/KNOWLEDGE-GRAPH.md
- .agent-spec/CONSTITUTION.md

## Open Decisions Requiring Developer Input
- Project type and tech stack (update PROJECT-INDEX.md)
EOF
echo -e "  ✅ Created .agent-spec/SESSION-SNAPSHOT.md"

# Knowledge Graph (empty)
if [ ! -f "${PROJECT_ROOT}/.agent-spec/graph/knowledge-graph.json" ]; then
  cat > "${PROJECT_ROOT}/.agent-spec/graph/knowledge-graph.json" << EOF
{
  "version": "1.0",
  "project": "$(basename "${PROJECT_ROOT}")",
  "generated": "${DATETIME}",
  "generator": "agent-spec-init",
  "nodes": [],
  "edges": [],
  "note": "Run agent-spec index --graphify to populate from codebase"
}
EOF
  echo -e "  ✅ Created .agent-spec/graph/knowledge-graph.json"
fi

if [ ! -f "${PROJECT_ROOT}/.agent-spec/graph/KNOWLEDGE-GRAPH.md" ]; then
  cat > "${PROJECT_ROOT}/.agent-spec/graph/KNOWLEDGE-GRAPH.md" << EOF
# Knowledge Graph

> Generated by agent-spec. Run \`agent-spec index --graphify\` to auto-populate.

## Dependency Graph

\`\`\`mermaid
graph TD
  A[$(basename "${PROJECT_ROOT}")] --> B[...]
\`\`\`

## Node Inventory
| Node | Type | Path | Dependencies |
|------|------|------|-------------|
| | | | |

## Last Indexed
${DATE} — Initial (empty). Run \`agent-spec index\` to populate.
EOF
  echo -e "  ✅ Created .agent-spec/graph/KNOWLEDGE-GRAPH.md"
fi

# Tech Debt Register
if [ ! -f "${PROJECT_ROOT}/.agent-spec/TECH-DEBT-REGISTER.md" ]; then
  cp "${AGENT_SPEC_HOME}/context/TECH-DEBT-REGISTER.md" \
     "${PROJECT_ROOT}/.agent-spec/TECH-DEBT-REGISTER.md"
  echo -e "  ✅ Created .agent-spec/TECH-DEBT-REGISTER.md"
fi

# ---------------------------------------------------------------------------
# 1b. Install framework folders → .agent-spec/
# ---------------------------------------------------------------------------
echo -e "${YELLOW}[1b/6] Installing framework folders...${NC}"
FRAMEWORK_FOLDERS=("personas" "pipeline" "rules" "coding-standards" "anti-hallucination" "memory" "templates")

for folder in "${FRAMEWORK_FOLDERS[@]}"; do
  if [ -d "${AGENT_SPEC_HOME}/${folder}" ]; then
    mkdir -p "${PROJECT_ROOT}/.agent-spec/${folder}"
    cp -R "${AGENT_SPEC_HOME}/${folder}/"* "${PROJECT_ROOT}/.agent-spec/${folder}/"
    echo -e "  ✅ Installed .agent-spec/${folder}/"
  fi
done

echo -e "  ✅ Created .agent-spec/sdlc/ directory"

# ---------------------------------------------------------------------------
# 2. Install root agent config files
# ---------------------------------------------------------------------------
echo ""
echo -e "${YELLOW}[2/6] Installing agent config files...${NC}"

install_with_merge() {
  local src="$1"
  local dest="$2"
  local agent_name="$3"

  if [ -f "${dest}" ]; then
    # Inject agent-spec reference if not already present
    if ! grep -q "agent-spec" "${dest}"; then
      echo "" >> "${dest}"
      echo "---" >> "${dest}"
      echo "<!-- agent-spec rules loaded from ${AGENT_SPEC_HOME} -->" >> "${dest}"
      echo "<!-- See AGENTS.md for full agent-spec configuration -->" >> "${dest}"
      echo -e "  ✅ Merged agent-spec reference into existing ${agent_name}"
    else
      echo -e "  ⏭️  Skipped ${agent_name} (agent-spec already present)"
    fi
  else
    if [ "${src}" != "${dest}" ]; then
      cp "${src}" "${dest}"
      echo -e "  ✅ Created ${agent_name}"
    fi
  fi
}

install_with_merge "${AGENT_SPEC_HOME}/AGENTS.md"  "${PROJECT_ROOT}/AGENTS.md"  "AGENTS.md"
install_with_merge "${AGENT_SPEC_HOME}/CLAUDE.md"  "${PROJECT_ROOT}/CLAUDE.md"  "CLAUDE.md"
install_with_merge "${AGENT_SPEC_HOME}/GEMINI.md"  "${PROJECT_ROOT}/GEMINI.md"  "GEMINI.md"
install_with_merge "${AGENT_SPEC_HOME}/CURSOR.md"  "${PROJECT_ROOT}/CURSOR.md"  "CURSOR.md"
install_with_merge "${AGENT_SPEC_HOME}/COPILOT.md" "${PROJECT_ROOT}/COPILOT.md" "COPILOT.md"

# ---------------------------------------------------------------------------
# 3. Install Claude skills → .claude/skills/
# ---------------------------------------------------------------------------
echo ""
echo -e "${YELLOW}[3/7] Installing Claude skills → .claude/skills/...${NC}"
mkdir -p "${PROJECT_ROOT}/.claude/skills"
for skill_dir in "${AGENT_SPEC_HOME}/skills/claude/"*/; do
  if [ -d "${skill_dir}" ]; then
    skill_name=$(basename "${skill_dir}")
    mkdir -p "${PROJECT_ROOT}/.claude/skills/${skill_name}"
    if [ ! -f "${PROJECT_ROOT}/.claude/skills/${skill_name}/SKILL.md" ] || [ "$FORCE_OVERWRITE" = "true" ]; then
      if [ "${skill_dir}/SKILL.md" != "${PROJECT_ROOT}/.claude/skills/${skill_name}/SKILL.md" ]; then
        cp "${skill_dir}/SKILL.md" "${PROJECT_ROOT}/.claude/skills/${skill_name}/SKILL.md"
      fi
    fi
  fi
done
echo -e "  ✅ Installed Claude skills"

# ---------------------------------------------------------------------------
# 4. Install GitHub Copilot / Codex skills → .github/
# ---------------------------------------------------------------------------
echo ""
echo -e "${YELLOW}[4/8] Installing GitHub Copilot instructions...${NC}"
mkdir -p "${PROJECT_ROOT}/.github"
if [ ! -f "${PROJECT_ROOT}/.github/copilot-instructions.md" ] || [ "$FORCE_OVERWRITE" = "true" ]; then
  if [ "${AGENT_SPEC_HOME}/.github/copilot-instructions.md" != "${PROJECT_ROOT}/.github/copilot-instructions.md" ]; then
    cp "${AGENT_SPEC_HOME}/.github/copilot-instructions.md" "${PROJECT_ROOT}/.github/copilot-instructions.md"
  fi
fi
echo -e "  ✅ Installed GitHub Copilot instructions"

# ---------------------------------------------------------------------------
# 5. Install Cursor skills → .cursor/rules/
# ---------------------------------------------------------------------------
echo ""
echo -e "${YELLOW}[5/8] Installing Cursor rules...${NC}"
mkdir -p "${PROJECT_ROOT}/.cursor/rules"

# Copy cursor rules (always-on)
cat "${AGENT_SPEC_HOME}/CURSOR.md" > "${PROJECT_ROOT}/.cursor/rules/agent-spec-rules.md"
echo -e "  ✅ Installed .cursor/rules/agent-spec-rules.md"

# Copy cursor skills
for skill in "${AGENT_SPEC_HOME}/skills/cursor/"*.md; do
  skill_name=$(basename "${skill}")
  if [ ! -f "${PROJECT_ROOT}/.cursor/rules/${skill_name}" ] || [ "$FORCE_OVERWRITE" = "true" ]; then
    if [ "${skill}" != "${PROJECT_ROOT}/.cursor/rules/${skill_name}" ]; then
      cp "${skill}" "${PROJECT_ROOT}/.cursor/rules/${skill_name}"
    fi
  fi
done
echo -e "  ✅ Installed Cursor rules"

# ---------------------------------------------------------------------------
# 6. Install Windsurf rules → .windsurfrules
# ---------------------------------------------------------------------------
echo ""
echo -e "${YELLOW}[6/8] Installing Windsurf rules...${NC}"
if [ ! -f "${PROJECT_ROOT}/.windsurfrules" ] || [ "$FORCE_OVERWRITE" = "true" ]; then
  if [ "${AGENT_SPEC_HOME}/.windsurfrules" != "${PROJECT_ROOT}/.windsurfrules" ]; then
    cp "${AGENT_SPEC_HOME}/.windsurfrules" "${PROJECT_ROOT}/.windsurfrules"
  fi
fi
echo -e "  ✅ Installed Windsurf rules"

# ---------------------------------------------------------------------------
# 7. Install Generic skills (for Antigravity/Gemini) → .agents/skills/
# ---------------------------------------------------------------------------
echo ""
echo -e "${YELLOW}[7/8] Installing generic skills → .agents/skills/...${NC}"
mkdir -p "${PROJECT_ROOT}/.agents/skills"
for skill_dir in "${AGENT_SPEC_HOME}/skills/generic/"*/; do
  if [ -d "${skill_dir}" ]; then
    skill_name=$(basename "${skill_dir}")
    mkdir -p "${PROJECT_ROOT}/.agents/skills/${skill_name}"
    if [ ! -f "${PROJECT_ROOT}/.agents/skills/${skill_name}/SKILL.md" ] || [ "$FORCE_OVERWRITE" = "true" ]; then
      if [ "${skill_dir}/SKILL.md" != "${PROJECT_ROOT}/.agents/skills/${skill_name}/SKILL.md" ]; then
        cp "${skill_dir}/SKILL.md" "${PROJECT_ROOT}/.agents/skills/${skill_name}/SKILL.md"
      fi
    fi
  fi
done
echo -e "  ✅ Installed generic skills"

# ---------------------------------------------------------------------------
# 8. Install Framework Binaries → .agent-spec/bin/
# ---------------------------------------------------------------------------
echo ""
echo -e "${YELLOW}[8/8] Installing framework binaries → .agent-spec/bin/...${NC}"
mkdir -p "${PROJECT_ROOT}/.agent-spec/bin"
if [ "${AGENT_SPEC_HOME}" != "${PROJECT_ROOT}" ]; then
  cp "${AGENT_SPEC_HOME}/bin/agent-spec-index.sh" "${PROJECT_ROOT}/.agent-spec/bin/agent-spec-index"
  cp "${AGENT_SPEC_HOME}/bin/agent-spec-new.sh"   "${PROJECT_ROOT}/.agent-spec/bin/agent-spec-new"
  cp "${AGENT_SPEC_HOME}/bin/graphify-build.py"   "${PROJECT_ROOT}/.agent-spec/bin/graphify-build.py"
  cp "${AGENT_SPEC_HOME}/bin/graphify-cli.py"     "${PROJECT_ROOT}/.agent-spec/bin/graphify-cli.py"
  chmod +x "${PROJECT_ROOT}/.agent-spec/bin/"*
fi
echo -e "  ✅ Installed agent-spec binaries"

# ---------------------------------------------------------------------------
# 9. Auto-Generate Project Index
# ---------------------------------------------------------------------------
echo ""
echo -e "${YELLOW}[9/9] Auto-detecting project architecture...${NC}"
if [ -f "${PROJECT_ROOT}/.agent-spec/bin/graphify-build.py" ]; then
  python3 "${PROJECT_ROOT}/.agent-spec/bin/graphify-build.py"
else
  python3 "${AGENT_SPEC_HOME}/bin/graphify-build.py"
fi
echo -e "  ✅ Project indexed successfully"


# ---------------------------------------------------------------------------
# Done
# ---------------------------------------------------------------------------
echo ""
echo -e "${GREEN}╔══════════════════════════════════════════╗${NC}"
echo -e "${GREEN}║        agent-spec initialized! 🎉        ║${NC}"
echo -e "${GREEN}╚══════════════════════════════════════════╝${NC}"
echo ""
echo "Next steps:"
echo -e "  ${YELLOW}1. RESTART Claude Code${NC} (or any agent CLI you had open in this project)"
echo "     Claude Code only watches .claude/skills/ if the directory existed when the"
echo "     session started. If it was just created by this script, the skills will not"
echo "     appear until you restart — they are installed correctly either way."
echo "  2. Review:  .agent-spec/PROJECT-INDEX.md (Auto-generated)"
echo "  3. Run:     ./.agent-spec/bin/agent-spec-new  (to start SDLC from scratch)"
echo ""
echo "Available skills in Claude Code:"
echo "  /requirements  /tech-spec  /prd  /hld  /lld  /implement  /review"
echo "  /index-project  /snapshot  /solid-check  /debt"
echo "  /raw-code  /trim-noise  /dense  /verbose"
echo ""
