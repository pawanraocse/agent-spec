#!/usr/bin/env bash
# =============================================================================
# agent-spec-init.sh
# Initialize agent-spec framework in the current project directory.
# Usage: ./bin/agent-spec-init.sh [--agent claude|gemini|cursor|all]
# =============================================================================

set -eo pipefail # Remove -u to handle unbound BASH_SOURCE

GREEN='\033[0;32m'; BLUE='\033[0;34m'; YELLOW='\033[1;33m'; NC='\033[0m'

GITHUB_RAW_URL="https://raw.githubusercontent.com/pawanraocse/agent-spec/main"

# Detect if we are running locally or remotely
if [ -n "${BASH_SOURCE[0]:-}" ] && [ -f "${BASH_SOURCE[0]}" ]; then
  AGENT_SPEC_HOME="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
  MODE="LOCAL"
else
  AGENT_SPEC_HOME="/tmp/agent-spec-$(date +%s)"
  MODE="REMOTE"
  mkdir -p "${AGENT_SPEC_HOME}"
  echo -e "${YELLOW}Downloading framework from GitHub...${NC}"
  curl -sSL "https://github.com/pawanraocse/agent-spec/archive/refs/heads/main.tar.gz" | tar -xz -C "${AGENT_SPEC_HOME}" --strip-components=1
fi

# Cleanup on exit if remote
if [ "$MODE" = "REMOTE" ]; then
  trap 'rm -rf "${AGENT_SPEC_HOME}"' EXIT
fi

PROJECT_ROOT="$(pwd)"
DATE=$(date '+%Y-%m-%d')
DATETIME=$(date '+%Y-%m-%dT%H:%M:%S')
AGENT="${1:-all}"


echo -e "${BLUE}╔══════════════════════════════════════════╗${NC}"
echo -e "${BLUE}║         agent-spec init v1.0.0           ║${NC}"
echo -e "${BLUE}╚══════════════════════════════════════════╝${NC}"
echo ""
echo -e "📂 Project root: ${PROJECT_ROOT}"
echo -e "🏠 agent-spec home: ${AGENT_SPEC_HOME}"
echo ""

# ---------------------------------------------------------------------------
# 1. Create .agent-spec/ directory structure
# ---------------------------------------------------------------------------
echo -e "${YELLOW}[1/6] Creating .agent-spec/ directory...${NC}"
mkdir -p "${PROJECT_ROOT}/.agent-spec/graph"
mkdir -p "${PROJECT_ROOT}/.agent-spec/sdlc"

# Project Index
if [ ! -f "${PROJECT_ROOT}/.agent-spec/PROJECT-INDEX.md" ]; then
  cat > "${PROJECT_ROOT}/.agent-spec/PROJECT-INDEX.md" << EOF
# Project Index

> Generated by agent-spec init on ${DATE}
> Run \`agent-spec index --graphify\` to auto-populate from codebase.

## Project Overview
<!-- Describe this project in 2-3 sentences -->
**Name**: $(basename "${PROJECT_ROOT}")
**Type**: [web-app | api | library | monolith | microservice]
**Tech Stack**: [e.g., Java Spring Boot + Angular | Python FastAPI | Node.js + React]
**Status**: [active | maintenance | legacy]

## Modules / Services
<!-- Add one entry per module/service/package -->
| Module | Responsibility | Path | Last Updated |
|--------|---------------|------|-------------|
| | | | |

## Key Architectural Decisions
<!-- Link to ADRs or summarize decisions -->
- [ADR-001]: [Decision description]

## Known Technical Debt
<!-- Reference TECH-DEBT-REGISTER.md for details -->
| ID | Description | Severity | Owner |
|----|-------------|----------|-------|
| | | | |

## External Dependencies
<!-- Key third-party services, APIs, or libraries -->
| Name | Purpose | Version |
|------|---------|---------|
| | | |

## Active Sessions
| Date | Developer | Gate | Task |
|------|-----------|------|------|
| ${DATE} | | 1 (Discovery) | Initial setup |
EOF
  echo -e "  ✅ Created .agent-spec/PROJECT-INDEX.md"
fi

# Constitution
if [ ! -f "${PROJECT_ROOT}/.agent-spec/CONSTITUTION.md" ]; then
  cp "${AGENT_SPEC_HOME}/templates/project-constitution.md" \
     "${PROJECT_ROOT}/.agent-spec/CONSTITUTION.md"
  echo -e "  ✅ Created .agent-spec/CONSTITUTION.md"
fi

# Session Snapshot
cat > "${PROJECT_ROOT}/.agent-spec/SESSION-SNAPSHOT.md" << EOF
# Session Snapshot — ${DATETIME}

> Created by agent-spec init. Update this after every working session.

## Session Summary
Initial project setup with agent-spec framework.

## Current Pipeline Gate
Gate 1: DISCOVERY

## Last Task Completed
agent-spec initialization

## Files Changed
- (none yet)

## Open Items
- [ ] Fill in PROJECT-INDEX.md with project details
- [ ] Run \`agent-spec index --graphify\` to build knowledge graph
- [ ] Fill in .agent-spec/CONSTITUTION.md with project rules

## Next Session: Load These Files
- .agent-spec/PROJECT-INDEX.md
- .agent-spec/graph/KNOWLEDGE-GRAPH.md
- .agent-spec/CONSTITUTION.md

## Open Decisions Requiring Developer Input
- Project type and tech stack (update PROJECT-INDEX.md)
EOF
echo -e "  ✅ Created .agent-spec/SESSION-SNAPSHOT.md"

# Knowledge Graph (empty)
if [ ! -f "${PROJECT_ROOT}/.agent-spec/graph/knowledge-graph.json" ]; then
  cat > "${PROJECT_ROOT}/.agent-spec/graph/knowledge-graph.json" << EOF
{
  "version": "1.0",
  "project": "$(basename "${PROJECT_ROOT}")",
  "generated": "${DATETIME}",
  "generator": "agent-spec-init",
  "nodes": [],
  "edges": [],
  "note": "Run agent-spec index --graphify to populate from codebase"
}
EOF
  echo -e "  ✅ Created .agent-spec/graph/knowledge-graph.json"
fi

if [ ! -f "${PROJECT_ROOT}/.agent-spec/graph/KNOWLEDGE-GRAPH.md" ]; then
  cat > "${PROJECT_ROOT}/.agent-spec/graph/KNOWLEDGE-GRAPH.md" << EOF
# Knowledge Graph

> Generated by agent-spec. Run \`agent-spec index --graphify\` to auto-populate.

## Dependency Graph

\`\`\`mermaid
graph TD
  A[$(basename "${PROJECT_ROOT}")] --> B[...]
\`\`\`

## Node Inventory
| Node | Type | Path | Dependencies |
|------|------|------|-------------|
| | | | |

## Last Indexed
${DATE} — Initial (empty). Run \`agent-spec index\` to populate.
EOF
  echo -e "  ✅ Created .agent-spec/graph/KNOWLEDGE-GRAPH.md"
fi

# Tech Debt Register
if [ ! -f "${PROJECT_ROOT}/.agent-spec/TECH-DEBT-REGISTER.md" ]; then
  cp "${AGENT_SPEC_HOME}/context/TECH-DEBT-REGISTER.md" \
     "${PROJECT_ROOT}/.agent-spec/TECH-DEBT-REGISTER.md"
  echo -e "  ✅ Created .agent-spec/TECH-DEBT-REGISTER.md"
fi

echo -e "  ✅ Created .agent-spec/sdlc/ directory"

# ---------------------------------------------------------------------------
# 2. Install root agent config files
# ---------------------------------------------------------------------------
echo ""
echo -e "${YELLOW}[2/6] Installing agent config files...${NC}"

install_with_merge() {
  local src="$1"
  local dest="$2"
  local agent_name="$3"

  if [ -f "${dest}" ]; then
    # Inject agent-spec reference if not already present
    if ! grep -q "agent-spec" "${dest}"; then
      echo "" >> "${dest}"
      echo "---" >> "${dest}"
      echo "<!-- agent-spec rules loaded from ${AGENT_SPEC_HOME} -->" >> "${dest}"
      echo "<!-- See AGENTS.md for full agent-spec configuration -->" >> "${dest}"
      echo -e "  ✅ Merged agent-spec reference into existing ${agent_name}"
    else
      echo -e "  ⏭️  Skipped ${agent_name} (agent-spec already present)"
    fi
  else
    cp "${src}" "${dest}"
    echo -e "  ✅ Created ${agent_name}"
  fi
}

install_with_merge "${AGENT_SPEC_HOME}/AGENTS.md"  "${PROJECT_ROOT}/AGENTS.md"  "AGENTS.md"
install_with_merge "${AGENT_SPEC_HOME}/CLAUDE.md"  "${PROJECT_ROOT}/CLAUDE.md"  "CLAUDE.md"
install_with_merge "${AGENT_SPEC_HOME}/GEMINI.md"  "${PROJECT_ROOT}/GEMINI.md"  "GEMINI.md"
install_with_merge "${AGENT_SPEC_HOME}/CURSOR.md"  "${PROJECT_ROOT}/CURSOR.md"  "CURSOR.md"
install_with_merge "${AGENT_SPEC_HOME}/COPILOT.md" "${PROJECT_ROOT}/COPILOT.md" "COPILOT.md"

# ---------------------------------------------------------------------------
# 3. Install Claude skills → .claude/commands/
# ---------------------------------------------------------------------------
echo ""
echo -e "${YELLOW}[3/6] Installing Claude skills → .claude/commands/...${NC}"
mkdir -p "${PROJECT_ROOT}/.claude/commands"
for skill in "${AGENT_SPEC_HOME}/skills/claude/"*.md; do
  skill_name=$(basename "${skill}")
  cp "${skill}" "${PROJECT_ROOT}/.claude/commands/${skill_name}"
done
echo -e "  ✅ Installed $(ls "${PROJECT_ROOT}/.claude/commands/" | wc -l | tr -d ' ') Claude skills"

# ---------------------------------------------------------------------------
# 4. Install Gemini skills → .gemini/commands/
# ---------------------------------------------------------------------------
echo ""
echo -e "${YELLOW}[4/6] Installing Gemini skills → .gemini/commands/...${NC}"
mkdir -p "${PROJECT_ROOT}/.gemini/commands"
for skill in "${AGENT_SPEC_HOME}/skills/gemini/"*.toml; do
  skill_name=$(basename "${skill}")
  cp "${skill}" "${PROJECT_ROOT}/.gemini/commands/${skill_name}"
done
echo -e "  ✅ Installed $(ls "${PROJECT_ROOT}/.gemini/commands/" | wc -l | tr -d ' ') Gemini skills"

# ---------------------------------------------------------------------------
# 5. Install Cursor skills → .cursor/rules/ + .cursor/skills/
# ---------------------------------------------------------------------------
echo ""
echo -e "${YELLOW}[5/6] Installing Cursor skills...${NC}"
mkdir -p "${PROJECT_ROOT}/.cursor/rules"
mkdir -p "${PROJECT_ROOT}/.cursor/skills"

# Copy cursor rules (always-on)
cat "${AGENT_SPEC_HOME}/CURSOR.md" > "${PROJECT_ROOT}/.cursor/rules/agent-spec-rules.md"
echo -e "  ✅ Installed .cursor/rules/agent-spec-rules.md"

# Copy cursor skills
for skill in "${AGENT_SPEC_HOME}/skills/cursor/"*.md; do
  skill_name=$(basename "${skill}")
  cp "${skill}" "${PROJECT_ROOT}/.cursor/skills/${skill_name}"
done
echo -e "  ✅ Installed $(ls "${PROJECT_ROOT}/.cursor/skills/" | wc -l | tr -d ' ') Cursor skills"

# ---------------------------------------------------------------------------
# 6. Install Generic skills → .agents/skills/
# ---------------------------------------------------------------------------
echo ""
echo -e "${YELLOW}[6/6] Installing generic skills → .agents/skills/...${NC}"
mkdir -p "${PROJECT_ROOT}/.agents/skills"
for skill_dir in "${AGENT_SPEC_HOME}/skills/generic/"/*/; do
  if [ -d "${skill_dir}" ]; then
    skill_name=$(basename "${skill_dir}")
    mkdir -p "${PROJECT_ROOT}/.agents/skills/${skill_name}"
    cp "${skill_dir}/SKILL.md" "${PROJECT_ROOT}/.agents/skills/${skill_name}/SKILL.md"
  fi
done
echo -e "  ✅ Installed generic skills"

# ---------------------------------------------------------------------------
# Done
# ---------------------------------------------------------------------------
echo ""
echo -e "${GREEN}╔══════════════════════════════════════════╗${NC}"
echo -e "${GREEN}║        agent-spec initialized! 🎉        ║${NC}"
echo -e "${GREEN}╚══════════════════════════════════════════╝${NC}"
echo ""
echo "Next steps:"
echo "  1. Fill in: .agent-spec/PROJECT-INDEX.md"
echo "  2. Run:     agent-spec index --graphify  (if existing project)"
echo "  3. Or run:  agent-spec new               (to start SDLC from scratch)"
echo ""
echo "Available skills in Claude Code:"
echo "  /requirements  /tech-spec  /prd  /hld  /lld  /implement  /review"
echo "  /index-project  /snapshot  /solid-check  /debt"
echo "  /raw-code  /trim-noise  /dense  /verbose"
echo ""
