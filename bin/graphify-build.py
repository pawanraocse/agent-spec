#!/usr/bin/env python3
import os
import json
import re
from datetime import datetime

PROJECT_ROOT = os.getcwd()
OUTPUT_DIR = os.path.join(PROJECT_ROOT, ".agent-spec", "graph")

# Regex patterns for common import syntax
IMPORT_PATTERNS = [
    r'^import\s+[\'"]([^\'"]+)[\'"]',              # JS/TS/Go
    r'^from\s+([^\s]+)\s+import',                   # Python
    r'^import\s+([^\s]+)',                          # Python/Java
    r'require\s*\(\s*[\'"]([^\'"]+)[\'"]\s*\)',     # JS/Node
    r'^#include\s*[<"]([^>"]+)[>"]'                 # C/C++
]

EXCLUDE_DIRS = {'.git', 'node_modules', 'target', 'dist', 'build', 'venv', '.venv', '.idea', '__pycache__', '.agent-spec'}
ALLOWED_EXTS = {'.py', '.java', '.ts', '.js', '.go', '.cpp', '.c', '.h'}

def should_process(filepath):
    ext = os.path.splitext(filepath)[1]
    return ext in ALLOWED_EXTS

def detect_tech_stack():
    stack = "Unknown"
    
    if os.path.exists(os.path.join(PROJECT_ROOT, "pom.xml")):
        stack = "Java (Maven)"
        try:
            with open(os.path.join(PROJECT_ROOT, "pom.xml"), "r") as f:
                if "spring-boot" in f.read():
                    stack = "Java Spring Boot"
        except: pass
    elif os.path.exists(os.path.join(PROJECT_ROOT, "package.json")):
        stack = "Node.js"
        try:
            with open(os.path.join(PROJECT_ROOT, "package.json"), "r") as f:
                content = f.read()
                if "angular" in content: stack += " + Angular"
                elif "react" in content: stack += " + React"
                elif "next" in content: stack += " + Next.js"
                elif "vue" in content: stack += " + Vue"
        except: pass
    elif os.path.exists(os.path.join(PROJECT_ROOT, "requirements.txt")) or os.path.exists(os.path.join(PROJECT_ROOT, "pyproject.toml")):
        stack = "Python"
        try:
            with open(os.path.join(PROJECT_ROOT, "requirements.txt"), "r") as f:
                content = f.read()
                if "django" in content.lower(): stack += " (Django)"
                elif "fastapi" in content.lower(): stack += " (FastAPI)"
                elif "flask" in content.lower(): stack += " (Flask)"
        except: pass
    elif os.path.exists(os.path.join(PROJECT_ROOT, "go.mod")):
        stack = "Go"
        
    return stack

def extract_imports(filepath):
    imports = set()
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            content = f.read()
            for pattern in IMPORT_PATTERNS:
                matches = re.finditer(pattern, content, re.MULTILINE)
                for match in matches:
                    imports.add(match.group(1))
    except Exception:
        pass # Skip unreadable files
    return list(imports)

def build_graph():
    nodes = []
    edges = []
    
    stats = {"java_files": 0, "ts_files": 0, "test_files": 0, "py_files": 0, "go_files": 0}
    
    modules = set()
    
    for root, dirs, files in os.walk(PROJECT_ROOT):
        # Exclude directories
        dirs[:] = [d for d in dirs if d not in EXCLUDE_DIRS]
        
        # Track top-level or important modules
        rel_root = os.path.relpath(root, PROJECT_ROOT)
        if rel_root != "." and not os.path.sep in rel_root:
            modules.add(rel_root)
            
        for file in files:
            filepath = os.path.join(root, file)
            if not should_process(filepath):
                continue
                
            rel_path = os.path.relpath(filepath, PROJECT_ROOT)
            ext = os.path.splitext(file)[1]
            
            # Update stats
            if ext == '.java': stats['java_files'] += 1
            elif ext in ['.ts', '.js']: stats['ts_files'] += 1
            elif ext == '.py': stats['py_files'] += 1
            elif ext == '.go': stats['go_files'] += 1
            
            if 'test' in file.lower() or 'spec' in file.lower():
                stats['test_files'] += 1
                
            imports = extract_imports(filepath)
            
            nodes.append({
                "id": rel_path,
                "type": "file",
                "path": rel_path
            })
            
            for imp in imports:
                edges.append({
                    "source": rel_path,
                    "target": imp,
                    "type": "imports"
                })
                
    return nodes, edges, stats, list(modules)

def write_project_index(stack, modules):
    index_path = os.path.join(PROJECT_ROOT, ".agent-spec", "PROJECT-INDEX.md")
    
    # Generate module table
    module_rows = ""
    for mod in sorted(modules):
        module_rows += f"| `{mod}/` | Auto-detected module | | |\n"
        
    if not module_rows:
        module_rows = "| | [TODO: AI could not auto-detect modules] | | |\n"

    date_str = datetime.now().strftime('%Y-%m-%d')
    content = f"""# Project Index

> Generated by agent-spec on {date_str}

## Project Overview
**Name**: {os.path.basename(PROJECT_ROOT)}
**Type**: [TODO: AI could not auto-detect, please ask user if web-app, api, or library]
**Tech Stack**: {stack}
**Status**: active

## Modules / Services
| Module | Responsibility | Path | Last Updated |
|--------|---------------|------|-------------|
{module_rows}

## Key Architectural Decisions
- [TODO: Ask user if any ADRs exist]

## Known Technical Debt
- [TODO: Scan for tech debt or ask user]

## External Dependencies
- [TODO: AI could not auto-detect 3rd party APIs, please ask user]

## Active Sessions
| Date | Developer | Gate | Task |
|------|-----------|------|------|
| {date_str} | | 1 (Discovery) | Initial auto-indexing |
"""
    with open(index_path, 'w') as f:
        f.write(content)

if __name__ == "__main__":
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    os.makedirs(os.path.join(PROJECT_ROOT, ".agent-spec"), exist_ok=True)
    
    print("Detecting tech stack...")
    stack = detect_tech_stack()
    print(f"  -> {stack}")
    
    print("Building knowledge graph dependencies...")
    nodes, edges, stats, modules = build_graph()
    
    write_project_index(stack, modules)
    print("Auto-generated PROJECT-INDEX.md")
    
    graph_data = {
        "version": "2.0",
        "project": os.path.basename(PROJECT_ROOT),
        "generated": datetime.now().isoformat(),
        "generator": "graphify-build-automated",
        "stats": stats,
        "nodes": nodes,
        "edges": edges,
        "note": "Automatically populated via AST/Regex extraction."
    }
    
    out_file = os.path.join(OUTPUT_DIR, "knowledge-graph.json")
    with open(out_file, 'w') as f:
        json.dump(graph_data, f, indent=2)
        
    print(f"Graph built successfully. Found {len(nodes)} files and {len(edges)} dependencies.")
    print(f"Output saved to {out_file}")
